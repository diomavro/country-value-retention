def _nasa_val(year: int, sector: str, item: str, direct: str = "PAID") -> float:
    d = _nasa()
    x = d[(d.TIME_PERIOD == year) & (d.sector == sector) & (d.na_item == item) & (d.direct == direct)]["OBS_VALUE"].dropna()
    if x.empty:
        raise KeyError(f"nasa_10_nf_tr {sector} {item} {direct} {year} missing")
    return float(x.iloc[0])


def corporate_nos(year: int) -> float:
    """Net operating surplus of non-financial corporations (S11): excludes mixed income, imputed
    rent and finance, whose FATS coverage changes in 2021."""
    return _nasa_val(year, "S11", "B2A3G") - _nasa_val(year, "S11", "P51C")


def corporate_ratios(year: int, rho_basis: str = "d41_gross") -> dict[str, float]:
    """Depreciation and interest per euro of gross operating surplus of non-financial corporations.

    Corporate-sector ratios (not industry ones) are used because industry B2A3G includes the
    mixed income of the self-employed, which foreign-controlled firms do not have.

    Interest (rho), central choice: S11 interest paid (D41, after the FISIM adjustment, gross),
    per euro of S11 GOS - the interest the average non-financial firm owes on its surplus.
    Interest *received* is not netted: receipts from abroad are not value generated in Cyprus
    and netting would credit them to foreign owners.  Variants: "d41_net" (paid - received),
    "d41g_gross" (actual interest before FISIM: c + rho >= 0.996 in 2010-2015, i.e. (almost) no
    profit; 11-29% of surplus left in 2016-2020; above the central ratio in 2021-2022 and below it in 2023), "none".  Interest is deducted only for non-financial industries.

    intra_group_share: BoP FDI debt interest paid by S1V / S11 D41 paid: the share of firms'
    interest that goes to their own foreign parents or affiliates (includes pass-through, so an
    upper bound).
    """
    b11, b12 = _nasa_val(year, "S11", "B2A3G"), _nasa_val(year, "S12", "B2A3G")
    d41 = _nasa_val(year, "S11", "D41")
    if rho_basis == "d41_gross":
        rho = d41 / b11
    elif rho_basis == "d41_net":
        rho = (d41 - _nasa_val(year, "S11", "D41", "RECV")) / b11
    elif rho_basis == "d41g_gross":
        rho = _nasa_val(year, "S11", "D41G") / b11
    elif rho_basis == "none":
        rho = 0.0
    else:
        raise ValueError(rho_basis)
    debt, _ = _bop(year, "S1V", "D41__D__FLA", "DEB")
    return {
        "cfc_nonfin": _nasa_val(year, "S11", "P51C") / b11,
        "interest_nonfin": max(rho, 0.0),
        "intra_group_share": min(debt / d41, 1.0) if pd.notna(debt) and d41 > 0 else 0.0,
        "cfc_fin": _nasa_val(year, "S12", "P51C") / b12,
        "employer_ssc_share": _nasa_val(year, "S1", "D12") / _nasa_val(year, "S1", "D1"),
        "household_interest_share": _nasa_val(year, "S14_S15", "D41") / (_nasa_val(year, "S14_S15", "D41") + d41),
    }


def gdp(year: int) -> float:
    return float(_sector().loc[(year, "S1"), "B1GQ"])


def _row(mech, partner, industry, value, status, method, source, conf):
    return {
        "mechanism": mech,
        "partner": partner,
        "industry": industry,
        "value": float(value),
        "status": status,
        "methodology": method,
        "source": source,
        "confidence_level": conf,
    }


def _alloc(total: float, weights: pd.Series) -> pd.Series:
    w = weights.clip(lower=0)
    return total * w / w.sum() if w.sum() > 0 else w * 0


def _partner_shares(values: pd.Series, total: float) -> pd.Series:
    """Published country values; the unpublished remainder goes to an explicit bucket."""
    v = values.dropna()
    v = v[v > 0]
    rest = total - v.sum()
    if rest < -1e-6 * max(total, 1):
        v = (
            v * total / v.sum()
        )  # published parts exceed total (rounding/revisions): rescale
        rest = 0.0
    out = pd.concat([v, pd.Series({"CONFIDENTIAL_PARTNERS": max(rest, 0.0)})])
    return out[out > 0] / total if total > 0 else out * 0


# Two-letter codes in Eurostat's PARTNER list that are aggregates, not economies (checked
# against the codelist 2026-09-24): counting them beside their members would double count.
TWO_LETTER_AGGREGATES = {"EU", "EA", "FZ"}  # EU, euro area, Franc Zone


def _is_country(code: str) -> bool:
    return len(code) == 2 and code.isalpha() and code not in TWO_LETTER_AGGREGATES


# ---------- M1 compensation of non-resident employees ----------
def m1_labour(year: int, na: pd.DataFrame) -> tuple[list[dict], dict]:
    """Compensation of non-resident employees net of Cypriot employer social contributions.

    D1 includes employers' social contributions paid to Cypriot social insurance; like the
    corporate tax deducted from foreign owners, that part accrues to Cyprus.  Taxes and
    contributions withheld from the workers themselves are not observed (BoP D5/D61 credits are
    zero) and are not deducted.
    """
    gross = float(_sector().loc[(year, "S2"), "D1REC"])  # received by RoW = paid by CY
    ssc = corporate_ratios(year)["employer_ssc_share"]
    total = gross * (1 - ssc)
    r = _one("bop_rem6__*.parquet")
    r = r[(r.bop_item == "D1") & (r.stk_flow == "DEB") & (r.TIME_PERIOD.astype(int) == year)]
    by = r[r.partner.map(_is_country) & (r.partner != _GEO)].set_index("partner")["OBS_VALUE"]
    shares = _partner_shares(by, gross)
    rows = []
    ind = _alloc(1.0, na["D1"])
    for p, s in shares.items():
        for k, w in ind[ind > 0].items():
            rows.append(
                _row(
                    "compensation_nonresident",
                    p,
                    k,
                    total * s * w,
                    "estimated",
                    f"S2 D1 (observed) x (1 - employer social contributions share {ssc:.3f}) x BoP bop_rem6 partner share (unpublished partners pooled) x industry share of D1",
                    f"{_sector_source_label()}; Eurostat bop_rem6; nasa_10_nf_tr",
                    "medium" if p != "CONFIDENTIAL_PARTNERS" else "low",
                )
            )
    return rows, {"labour_gross": gross, "labour_net": total, "employer_ssc_share": ssc}


