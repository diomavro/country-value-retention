"""Frame A estimator: who receives the value added generated in Cyprus in year t.

Builds an ``IncomeAccount`` (national accounts, 64 industries) and its outflow
table from official sources, one mechanism at a time.  Every outflow row
carries status/methodology/source so the tensor stays auditable.  Parameters
that are not observed (foreign equity share theta, corporate tax rate tau) are
explicit arguments so sensitivity analysis can vary them.

Mechanisms (see docs/methodology.md for the full rationale):

  M1 compensation_nonresident   CYSTAT S2 D1 (paid by CY) x BoP partner shares; industry ∝ D1_k
  M2 fdi_income                 FATS operating surplus of foreign-controlled firms, by section and
                                ultimate controlling country, net of depreciation and corporate tax,
                                x theta.  Before 2021 FATS excludes finance: foreign-owned banks enter
                                via BoP S122 FDI equity income instead.
  M3 other_investment_income    BoP interest/dividends paid by non-SPE sectors on portfolio and other
     portfolio_income           investment: S1V (firms, households) gross; S122 banks net of receipts.
     public_debt_interest       S13 general government, financed from the tax pool.
  M4 taxes_to_eu_institutions   CYSTAT S2 D2 received by the rest of the world.

Excluded by design: income paid by financial corporations other than MFIs
(S12M) — Cyprus's SPEs and captive financial units — which is pass-through
income not generated by Cypriot production.  It is reported separately.
"""

