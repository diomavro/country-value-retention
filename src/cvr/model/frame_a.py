@dataclass(frozen=True)
class Params:
    theta: float | None = None  # non-resident equity share; None = calibrated value (ownership_data.theta_central)
    tax: str = "statutory"  # "statutory", "none", or "eatr" (EC forward-looking effective rate; variant)
    include_ofc: bool = False  # sensitivity: include S12M (SPE-dominated) outflows
    consistent_scope: bool = False  # FATS sections B-N only in every year, banks via BoP -> no 2021 break
    banks_gross: bool = False  # sensitivity: banks' non-FDI interest paid abroad gross, not net of receipts
    bop_upper: bool = False  # sensitivity: foreign-owned profit = max(FATS-based, BoP FDI equity income paid)
    rho_basis: str = "d41_gross"  # interest deducted: "d41_gross" (central), "d41_net", "d41g_gross", "none" (variants)
    fats_na_level: bool = True  # where FATS all-owner GOS exceeds NA GOS: FATS foreign share x NA level (False = FATS level, variant)


@contextmanager
def country(geo: str, sector_source: str | None = None):
    """Run the estimator for `geo`.  `sector_source` "eurostat" makes Cyprus read its rest-of-world
    and GDP/GNI totals from nasa_10_nf_tr instead of CYSTAT (used by the regression test)."""
    global _GEO, _SECTOR_SOURCE
    prev = (_GEO, _SECTOR_SOURCE)
    src = sector_source or ("cystat" if geo == "CY" else "eurostat")
    if src == "cystat" and geo != "CY":
        raise ValueError("CYSTAT sector accounts exist for Cyprus only")
    _GEO, _SECTOR_SOURCE = geo, src
    _clear_caches()
    try:
        yield
    finally:
        _GEO, _SECTOR_SOURCE = prev
        _clear_caches()


def _clear_caches() -> None:
    for f in (_nama, _sector, _nasa, _bop_c6):
        f.cache_clear()


def _dir() -> Path:
    return EUROSTAT if _GEO == "CY" else EUROSTAT_EU


def _one(pattern: str) -> pd.DataFrame:
    """All files matching `pattern`, restricted to the current country."""
    files = sorted(glob.glob(str(_dir() / pattern)))
    if not files:
        raise FileNotFoundError(_dir() / pattern)
    d = pd.concat([pd.read_parquet(f) for f in files], ignore_index=True)
    d = d[d["geo"] == _GEO]
    if d.empty:
        raise FileNotFoundError(f"{pattern}: no rows for geo={_GEO}")
    # overlapping downloads may repeat an observation; two different values for one key would
    # otherwise be averaged or picked arbitrarily downstream
    key = [c for c in d.columns if c not in {"DATAFLOW", "LAST_UPDATE", "OBS_VALUE", "OBS_FLAG", "CONF_STATUS"}]
    d = d.drop_duplicates(subset=key + ["OBS_VALUE"])
    clash = d.duplicated(subset=key, keep=False)
    if clash.any():
        raise ValueError(f"{pattern} ({_GEO}): {int(clash.sum())} observations have conflicting values across files; delete the stale download")
    return d


@lru_cache(maxsize=None)
def _nama() -> pd.DataFrame:
    d = _one("nama_10_a64__*.parquet")
    d = d[d.unit == "CP_MEUR"].copy()
    d["TIME_PERIOD"] = d.TIME_PERIOD.astype(int)
    return d


NA_ITEMS = ["B1G", "D1", "D29X39", "P51C", "B2A3N"]


class SuppressedInput(KeyError):
    """An input the statistical office does not publish: the country-year is skipped, never filled in."""


def na_industry(year: int) -> pd.DataFrame:
    """B1G, D1, D29X39, P51C, B2A3N and B2A3G by canonical industry (EUR m).

    Where a country suppresses an industry (any of the five items missing), its whole section
    becomes one row coded by the section letter (e.g. 'C'), taken from the published section
    total: the unpublished industries are never imputed.  Cyprus publishes every industry.
    """
    d = _nama()
    d = d[d.TIME_PERIOD == year].pivot_table(
        index="nace_r2", columns="na_item", values="OBS_VALUE"
    ).reindex(columns=NA_ITEMS)
    pub: dict[str, str] = {}
    for k in d.index:
        if d.loc[k].notna().all():
            pub.setdefault(from_nama(k), k)
    codes = canon()
    missing = [c for c in codes if (c not in pub if c != "L68B" else not {"L68", "L68A"} <= pub.keys())]
    gaps = sorted({section(c) for c in missing})
    if "K" in gaps:
        raise SuppressedInput(f"{year}: finance (K) industries suppressed; banks cannot be placed")
    unpublished = [s_code for s_code in gaps if s_code not in pub]
    if unpublished:
        raise SuppressedInput(f"{year}: sections {', '.join(unpublished)} not published separately in the national accounts")
    index = []
    for c in codes:
        code = section(c) if section(c) in gaps else c
        if code not in index:
            index.append(code)
    out = pd.DataFrame(index=index, columns=NA_ITEMS, dtype=float)
    for code in index:
        if code == "L68B":
            out.loc[code] = (d.loc[pub["L68"]] - d.loc[pub["L68A"]]).values
        else:
            out.loc[code] = d.loc[pub[code]].values
    out["B2A3G"] = out["B2A3N"] + out["P51C"]
    out.attrs["collapsed_sections"] = gaps
    # imputed rent of owner-occupiers inside a collapsed real-estate row (its value added is published)
    l68a = next((k for k in d.index if from_nama(k) == "L68A"), None)
    # its operating surplus (B2A3N + P51C) where published, else its value added (an upper bound; Ireland)
    out.attrs["imputed_rent_in_L"] = imputed_rent_gos(d.loc[l68a]) if "L" in gaps and l68a else 0.0
    total = d.loc["TOTAL", "B1G"]
    if abs(out["B1G"].sum() - total) > 1.0:
        raise AssertionError(
            f"{year}: A64 industries sum to {out['B1G'].sum():.1f}, TOTAL {total:.1f}"
        )
    return out


@lru_cache(maxsize=None)
def _sector() -> pd.DataFrame:
    """Rest-of-world (S2) and total-economy (S1) items, indexed (year, sector), CYSTAT item names.

    Outside Cyprus they come from nasa_10_nf_tr: the S2 account is written from the rest of the
    world's side, so 'received by S2' (RECV) is what the country pays abroad (CYSTAT's D1REC etc.).
    """
    if _SECTOR_SOURCE == "cystat":
        s = pd.read_parquet(CYSTAT / "sector_accounts.parquet")
        return s.pivot_table(
            index=["reference_year", "sector"], columns="item", values="value"
        )
    d = _nasa()
    items = {("S2", "D1", "RECV"): "D1REC", ("S2", "D2", "RECV"): "D2REC", ("S2", "D4", "RECV"): "D4REC", ("S1", "B1GQ", "RECV"): "B1GQ", ("S1", "B5G", "RECV"): "B5G"}
    rows = []
    for (sec, item, direct), name in items.items():
        x = d[(d.sector == sec) & (d.na_item == item) & (d.direct == direct)]
        rows += [(int(t), sec, name, v) for t, v in zip(x.TIME_PERIOD, x.OBS_VALUE)]
    s = pd.DataFrame(rows, columns=["reference_year", "sector", "item", "value"])
    return s.pivot_table(index=["reference_year", "sector"], columns="item", values="value")


def imputed_rent_gos(r: pd.Series) -> float:
    """Operating surplus of imputed rent (B2A3N + P51C) where published, else its value added
    (an upper bound: Ireland publishes only that), else 0."""
    if pd.notna(r.get("B2A3N")) and pd.notna(r.get("P51C")):
        return float(r["B2A3N"] + r["P51C"])
    return float(r["B1G"]) if pd.notna(r.get("B1G")) else 0.0


def market_gos(na: pd.DataFrame) -> pd.Series:
    """Operating surplus that can belong to firms: imputed rent of owner-occupiers excluded
    (dropped as L68A, or subtracted from a collapsed real-estate row L)."""
    g = na["B2A3G"].drop(index=["L68A"], errors="ignore").copy()
    if "L" in g.index:
        g["L"] = max(g["L"] - na.attrs.get("imputed_rent_in_L", 0.0), 0.0)
    return g


def _sector_source_label() -> str:
    return "CYSTAT 0630030E" if _SECTOR_SOURCE == "cystat" else "Eurostat nasa_10_nf_tr"


@lru_cache(maxsize=None)
def _nasa() -> pd.DataFrame:
    d = _one("nasa_10_nf_tr__*.parquet")
    d = d[d.unit == "CP_MEUR"].copy()
    d["TIME_PERIOD"] = d.TIME_PERIOD.astype(int)
